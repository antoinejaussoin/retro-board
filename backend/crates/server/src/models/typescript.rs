//! TypeScript bindings for the socket and board contract.

use ts_rs::TS;

use super::{
    Board, ChatIn, ColumnDefinition, DeleteGroupPayload, DeletePostPayload, GroupDraft,
    GroupUpdate, IdOnly, IncomingGroup, IncomingPost, LikePayload, Message, Participant, Post,
    PostDraft, PostGroup, PostUpdate, ReceiveCancelVotesPayload, ReceiveLikePayload,
    SessionMetadata, SessionOptions, SessionSettings, SettingsPayload, TimerStartPayload, User,
    UserReadyPayload, VoteExtract, WsError, WsMessage,
};

const HEADER: &str = "// Generated by `cargo run -p retrospected-server --bin retrospected-export-types`.\n// Do not edit.\n\n";

/// Render the frontend contract as one TypeScript module.
#[must_use]
pub fn export_typescript() -> String {
    let cfg = ts_rs::Config::new().with_large_int("number");
    let decls = [
        User::decl(&cfg),
        SessionOptions::decl(&cfg),
        ColumnDefinition::decl(&cfg),
        VoteExtract::decl(&cfg),
        Post::decl(&cfg),
        PostGroup::decl(&cfg),
        Message::decl(&cfg),
        Board::decl(&cfg),
        Participant::decl(&cfg),
        SessionMetadata::decl(&cfg),
        SessionSettings::decl(&cfg),
        PostDraft::decl(&cfg),
        PostUpdate::decl(&cfg),
        IdOnly::decl(&cfg),
        IncomingPost::decl(&cfg),
        IncomingGroup::decl(&cfg),
        GroupDraft::decl(&cfg),
        GroupUpdate::decl(&cfg),
        LikePayload::decl(&cfg),
        DeletePostPayload::decl(&cfg),
        DeleteGroupPayload::decl(&cfg),
        SettingsPayload::decl(&cfg),
        ChatIn::decl(&cfg),
        WsError::decl(&cfg),
        ReceiveLikePayload::decl(&cfg),
        ReceiveCancelVotesPayload::decl(&cfg),
        TimerStartPayload::decl(&cfg),
        UserReadyPayload::decl(&cfg),
        WsMessage::<String>::decl(&cfg),
    ];
    let mut out = String::from(HEADER);
    for decl in decls {
        out.push_str("export ");
        out.push_str(decl.trim());
        out.push('\n');
    }
    out.push_str("export type WsCancelVotesPayload = WsDeletePostPayload;\n");
    out
}

#[cfg(test)]
mod tests {
    use super::export_typescript;

    #[test]
    fn generated_typescript_matches_frontend() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../../frontend/src/common/generated.ts");
        let committed = std::fs::read_to_string(&path).unwrap_or_default();
        assert_eq!(
            committed,
            export_typescript(),
            "run cargo run -p retrospected-server --bin retrospected-export-types"
        );
    }
}
